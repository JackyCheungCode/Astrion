-- Persist AI acquisition task drafts with strict workspace isolation.
begin;

create table if not exists public.ai_acquisition_tasks (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  task_number bigint generated by default as identity,
  name text not null check (char_length(trim(name)) between 1 and 160),
  status text not null default 'draft' check (status in ('draft','ready','running','completed','failed','archived')),
  audience text not null check (audience in ('b2b','b2c','both')),
  region text not null,
  industry text not null,
  company_size text,
  intent_signal text not null default 'all',
  provider_selection text[] not null default array['serper','tavily']::text[]
    check (provider_selection <@ array['serper','tavily']::text[] and cardinality(provider_selection) > 0),
  target_volume integer not null default 10 check (target_volume between 1 and 10),
  research_enabled boolean not null default true,
  evidence_scoring_enabled boolean not null default true,
  verified_sources_only boolean not null default false,
  company_offering text not null default '',
  value_proposition text not null default '',
  ideal_customer_notes text not null default '',
  excluded_targets text not null default '',
  created_by uuid not null default auth.uid() references auth.users(id),
  updated_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, task_number)
);

create index if not exists ai_acquisition_tasks_workspace_updated_idx
  on public.ai_acquisition_tasks(workspace_id, updated_at desc);

alter table public.ai_acquisition_tasks enable row level security;
drop policy if exists ai_acquisition_tasks_member_select on public.ai_acquisition_tasks;
create policy ai_acquisition_tasks_member_select on public.ai_acquisition_tasks
  for select to authenticated using (private.is_workspace_member(workspace_id));
drop policy if exists ai_acquisition_tasks_editor_insert on public.ai_acquisition_tasks;
create policy ai_acquisition_tasks_editor_insert on public.ai_acquisition_tasks
  for insert to authenticated with check (
    private.has_workspace_role(workspace_id,array['owner','admin','sales_manager','sales_rep','marketing'])
    and created_by = (select auth.uid()) and updated_by = (select auth.uid())
  );
drop policy if exists ai_acquisition_tasks_editor_update on public.ai_acquisition_tasks;
create policy ai_acquisition_tasks_editor_update on public.ai_acquisition_tasks
  for update to authenticated
  using (private.has_workspace_role(workspace_id,array['owner','admin','sales_manager','sales_rep','marketing']))
  with check (
    private.has_workspace_role(workspace_id,array['owner','admin','sales_manager','sales_rep','marketing'])
    and updated_by = (select auth.uid())
  );
drop policy if exists ai_acquisition_tasks_admin_delete on public.ai_acquisition_tasks;
create policy ai_acquisition_tasks_admin_delete on public.ai_acquisition_tasks
  for delete to authenticated using (private.has_workspace_role(workspace_id,array['owner','admin','sales_manager']));

create or replace function public.set_ai_acquisition_task_updated_at()
returns trigger language plpgsql set search_path = ''
as $$
begin
  new.updated_at = now();
  new.updated_by = (select auth.uid());
  return new;
end;
$$;
drop trigger if exists ai_acquisition_tasks_updated_at on public.ai_acquisition_tasks;
create trigger ai_acquisition_tasks_updated_at
before update on public.ai_acquisition_tasks
for each row execute function public.set_ai_acquisition_task_updated_at();

grant select, insert, update, delete on public.ai_acquisition_tasks to authenticated;
commit;
